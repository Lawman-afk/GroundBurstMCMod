package dev.groundzero.client.manual;

import java.io.Reader;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;

import org.jspecify.annotations.Nullable;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;

import dev.groundzero.GroundZero;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.FileToIdConverter;
import net.minecraft.resources.Identifier;
import net.minecraft.server.packs.resources.Resource;
import net.minecraft.server.packs.resources.ResourceManager;
import net.minecraft.server.packs.resources.SimplePreparableReloadListener;
import net.minecraft.util.profiling.ProfilerFiller;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.Items;

/**
 * The Field Manual's content (DESIGN.md §24.2), loaded from {@code assets/groundzero/manual/} with the client's
 * resources: chapters in {@code chapters/<id>.json}, entries in {@code entries/<chapter>/<id>.json} (entry id
 * {@code <chapter>/<id>}). The files are generated by {@code tools/manual/content.py}.
 */
public final class Manual {
    /** A chapter: a group of entries with an icon and a short introduction. */
    public record Chapter(String id, String title, Item icon, int order, String text) {}

    /** An entry: a run of pages about one subject; {@code items} are the items whose tooltip leads here. */
    public record Entry(String id, String chapter, String title, Item icon, int order, List<Item> items, List<PageSpec> pages) {}

    /** One page as written in the content files; the screen lays it out (text may run onto further pages). */
    public interface PageSpec {
        String text();
    }

    public record TextSpec(String text) implements PageSpec {}

    public record SpotlightSpec(Item item, @Nullable String title, String text) implements PageSpec {}

    /** Every crafting-table (or furnace, with {@code smelting}) recipe that makes {@code item}. */
    public record CraftingSpec(Item item, boolean smelting, String text) implements PageSpec {}

    /** Machine recipes of {@code kind}, optionally only those making {@code item} or the fluid {@code fluid}. */
    public record MachineSpec(String kind, @Nullable Item item, @Nullable Identifier fluid, String text) implements PageSpec {}

    public record StructureSpec(Identifier structure, String text) implements PageSpec {}

    public record ImageSpec(Identifier image, int width, int height, String text) implements PageSpec {}

    public record TableSpec(@Nullable String title, List<List<String>> rows, String text) implements PageSpec {}

    public record LinksSpec(@Nullable String title, List<String> entries, String text) implements PageSpec {}

    private static final FileToIdConverter CHAPTERS = FileToIdConverter.json("manual/chapters");
    private static final FileToIdConverter ENTRIES = FileToIdConverter.json("manual/entries");

    private static List<Chapter> chapters = List.of();
    private static Map<String, Entry> entries = Map.of();
    private static Map<Item, Entry> byItem = Map.of();
    private static int generation;

    private Manual() {}

    /** Goes up each time the content reloads (an open book then lays its pages out again). */
    public static int generation() {
        return generation;
    }

    public static List<Chapter> chapters() {
        return chapters;
    }

    public static @Nullable Chapter chapter(String id) {
        for (Chapter c : chapters) {
            if (c.id().equals(id)) {
                return c;
            }
        }
        return null;
    }

    public static @Nullable Entry entry(String id) {
        return entries.get(id);
    }

    /** The chapter's entries in reading order. */
    public static List<Entry> entriesOf(String chapter) {
        return entries.values().stream().filter(e -> e.chapter().equals(chapter))
                .sorted(Comparator.comparingInt(Entry::order).thenComparing(Entry::title)).toList();
    }

    public static List<Entry> allEntries() {
        return List.copyOf(entries.values());
    }

    /** The entry about {@code item}, if any (for the tooltip key and for clicking items in recipes). */
    public static @Nullable Entry entryFor(Item item) {
        return byItem.get(item);
    }

    /** Loads the manual with the client's resources. */
    public static final class Loader extends SimplePreparableReloadListener<Loader.Data> {
        record Data(List<Chapter> chapters, Map<String, Entry> entries) {}

        @Override
        protected Data prepare(ResourceManager manager, ProfilerFiller profiler) {
            List<Chapter> chapters = new ArrayList<>();
            for (Map.Entry<Identifier, Resource> file : CHAPTERS.listMatchingResources(manager).entrySet()) {
                if (!file.getKey().getNamespace().equals(GroundZero.MODID)) {
                    continue;
                }
                String id = CHAPTERS.fileToId(file.getKey()).getPath();
                try (Reader reader = file.getValue().openAsReader()) {
                    JsonObject json = JsonParser.parseReader(reader).getAsJsonObject();
                    chapters.add(new Chapter(id, string(json, "title", id), item(json, "icon"), integer(json, "order"), string(json, "text", "")));
                } catch (Exception e) {
                    GroundZero.LOGGER.error("Field Manual: bad chapter {}", file.getKey(), e);
                }
            }
            chapters.sort(Comparator.comparingInt(Chapter::order));
            Map<String, Entry> entries = new LinkedHashMap<>();
            for (Map.Entry<Identifier, Resource> file : ENTRIES.listMatchingResources(manager).entrySet()) {
                if (!file.getKey().getNamespace().equals(GroundZero.MODID)) {
                    continue;
                }
                String id = ENTRIES.fileToId(file.getKey()).getPath();
                int slash = id.indexOf('/');
                if (slash < 0) {
                    GroundZero.LOGGER.error("Field Manual: entry {} is not inside a chapter folder", file.getKey());
                    continue;
                }
                try (Reader reader = file.getValue().openAsReader()) {
                    JsonObject json = JsonParser.parseReader(reader).getAsJsonObject();
                    List<Item> items = new ArrayList<>();
                    for (JsonElement e : array(json, "items")) {
                        items.add(item(e.getAsString()));
                    }
                    List<PageSpec> pages = new ArrayList<>();
                    for (JsonElement e : array(json, "pages")) {
                        pages.add(page(e.getAsJsonObject()));
                    }
                    entries.put(id, new Entry(id, id.substring(0, slash), string(json, "title", id), item(json, "icon"), integer(json, "order"),
                            List.copyOf(items), List.copyOf(pages)));
                } catch (Exception e) {
                    GroundZero.LOGGER.error("Field Manual: bad entry {}", file.getKey(), e);
                }
            }
            return new Data(List.copyOf(chapters), entries);
        }

        @Override
        protected void apply(Data data, ResourceManager manager, ProfilerFiller profiler) {
            chapters = data.chapters();
            entries = Map.copyOf(data.entries());
            Map<Item, Entry> items = new HashMap<>();
            for (Entry e : data.entries().values()) {
                for (Item item : e.items()) {
                    items.putIfAbsent(item, e);
                }
            }
            byItem = Map.copyOf(items);
            generation++;
        }
    }

    private static PageSpec page(JsonObject json) {
        String text = string(json, "text", "");
        String type = string(json, "type", "text").toLowerCase(Locale.ROOT);
        return switch (type) {
            case "text" -> new TextSpec(text);
            case "spotlight" -> new SpotlightSpec(item(json, "item"), json.has("title") ? json.get("title").getAsString() : null, text);
            case "crafting" -> new CraftingSpec(item(json, "item"), false, text);
            case "smelting" -> new CraftingSpec(item(json, "item"), true, text);
            case "machine" -> new MachineSpec(string(json, "kind", ""), json.has("item") ? item(json, "item") : null,
                    json.has("fluid") ? Identifier.parse(json.get("fluid").getAsString()) : null, text);
            case "structure" -> new StructureSpec(Identifier.parse(string(json, "structure", "")), text);
            case "image" -> new ImageSpec(Identifier.parse(string(json, "image", "")), integer(json, "width"), integer(json, "height"), text);
            case "table" -> {
                List<List<String>> rows = new ArrayList<>();
                for (JsonElement row : array(json, "rows")) {
                    List<String> cells = new ArrayList<>();
                    for (JsonElement cell : row.getAsJsonArray()) {
                        cells.add(cell.getAsString());
                    }
                    rows.add(List.copyOf(cells));
                }
                yield new TableSpec(json.has("title") ? json.get("title").getAsString() : null, List.copyOf(rows), text);
            }
            case "links" -> {
                List<String> links = new ArrayList<>();
                for (JsonElement e : array(json, "entries")) {
                    links.add(e.getAsString());
                }
                yield new LinksSpec(json.has("title") ? json.get("title").getAsString() : null, List.copyOf(links), text);
            }
            default -> throw new IllegalArgumentException("unknown page type " + type);
        };
    }

    private static String string(JsonObject json, String key, String fallback) {
        return json.has(key) ? json.get(key).getAsString() : fallback;
    }

    private static int integer(JsonObject json, String key) {
        return json.has(key) ? json.get(key).getAsInt() : 0;
    }

    private static JsonArray array(JsonObject json, String key) {
        return json.has(key) ? json.getAsJsonArray(key) : new JsonArray();
    }

    private static Item item(JsonObject json, String key) {
        return json.has(key) ? item(json.get(key).getAsString()) : Items.BOOK;
    }

    private static Item item(String id) {
        return BuiltInRegistries.ITEM.getOptional(Identifier.parse(id)).orElseGet(() -> {
            GroundZero.LOGGER.error("Field Manual: unknown item {}", id);
            return Items.BARRIER;
        });
    }
}
