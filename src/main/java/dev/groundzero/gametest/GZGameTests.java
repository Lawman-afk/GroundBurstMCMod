package dev.groundzero.gametest;

import java.util.ArrayList;
import java.util.List;
import java.util.function.Consumer;

import dev.groundzero.GroundZero;
import dev.groundzero.registry.GZBlocks;
import dev.groundzero.registry.GZItems;
import dev.groundzero.registry.GZLang;
import net.minecraft.core.Holder;
import net.minecraft.core.registries.Registries;
import net.minecraft.gametest.framework.FunctionGameTestInstance;
import net.minecraft.gametest.framework.GameTestHelper;
import net.minecraft.gametest.framework.TestData;
import net.minecraft.gametest.framework.TestEnvironmentDefinition;
import net.minecraft.resources.Identifier;
import net.minecraft.world.level.block.Blocks;
import net.neoforged.bus.api.IEventBus;
import net.neoforged.neoforge.event.RegisterGameTestsEvent;
import net.neoforged.neoforge.registries.DeferredHolder;
import net.neoforged.neoforge.registries.DeferredRegister;

/**
 * GameTest harness. Test functions live in the vanilla TEST_FUNCTION registry; test instances (function +
 * structure + timeout) are registered on {@link RegisterGameTestsEvent}. Run them all with
 * {@code gradlew runGameTestServer}, or in a dev world with {@code /test runall}.
 *
 * <p>Test structures are NBT templates under {@code data/groundzero/structure/gametest/}, generated by
 * {@code tools/structure}.
 */
public final class GZGameTests {
    public static final DeferredRegister<Consumer<GameTestHelper>> FUNCTIONS = DeferredRegister.create(Registries.TEST_FUNCTION, GroundZero.MODID);

    /** Structure with a 16x16 smooth-stone floor at y=0 and 15 blocks of air above. */
    public static final Identifier FLOOR_16 = GroundZero.id("gametest/floor_16");
    /** A solid 12x12x12 cube of stone (rock for ore features to replace). */
    public static final Identifier STONE_12 = GroundZero.id("gametest/stone_12");

    private static final List<TestSpec> SPECS = new ArrayList<>();

    private record TestSpec(DeferredHolder<Consumer<GameTestHelper>, Consumer<GameTestHelper>> function, Identifier structure, int maxTicks) {}

    static {
        test("harness_floor", FLOOR_16, 20, helper -> {
            helper.assertBlockPresent(Blocks.SMOOTH_STONE, 0, 0, 0);
            helper.assertBlockPresent(Blocks.SMOOTH_STONE, 15, 0, 15);
            helper.assertBlockPresent(Blocks.AIR, 7, 1, 7);
            helper.succeed();
        });

        test("registry_names_and_tabs", FLOOR_16, 20, helper -> {
            GZItems.ITEMS.getEntries().forEach(entry -> {
                var item = entry.get();
                helper.assertTrue(GZLang.has(item.getDescriptionId()), "Item has no English name: " + entry.getId());
            });
            GZBlocks.BLOCKS.getEntries().forEach(entry ->
                    helper.assertTrue(GZLang.has(entry.get().getDescriptionId()), "Block has no English name: " + entry.getId()));
            helper.succeed();
        });

        ResourceTests.register();
        MachineTests.register();
    }

    private GZGameTests() {}

    static void test(String name, Identifier structure, int maxTicks, Consumer<GameTestHelper> body) {
        SPECS.add(new TestSpec(FUNCTIONS.register(name, () -> body), structure, maxTicks));
    }

    public static void register(IEventBus modBus) {
        FUNCTIONS.register(modBus);
        modBus.addListener(GZGameTests::registerTests);
    }

    private static void registerTests(RegisterGameTestsEvent event) {
        Holder<TestEnvironmentDefinition<?>> environment = event.registerEnvironment(GroundZero.id("default"));
        for (TestSpec spec : SPECS) {
            TestData<Holder<TestEnvironmentDefinition<?>>> data = new TestData<>(environment, spec.structure(), spec.maxTicks(), 0, true);
            event.registerTest(spec.function().getId(), new FunctionGameTestInstance(spec.function().key(), data));
        }
    }
}
