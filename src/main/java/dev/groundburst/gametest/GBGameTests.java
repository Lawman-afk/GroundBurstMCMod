package dev.groundburst.gametest;

import java.util.ArrayList;
import java.util.List;
import java.util.function.Consumer;

import dev.groundburst.GroundBurst;
import dev.groundburst.registry.GBBlocks;
import dev.groundburst.registry.GBItems;
import dev.groundburst.registry.GBLang;
import net.minecraft.gametest.framework.GameTestHelper;
import net.minecraft.resources.Identifier;
import net.minecraft.world.level.block.Blocks;
import net.neoforged.bus.api.IEventBus;

/**
 * GameTest harness: every test, a function run over a structure within a timeout, listed here; how they reach the
 * game is {@link GameTestRegistration}'s (each version its own). Run them all with {@code gradlew runGameTestServer},
 * or in a dev world with {@code /test runall}.
 *
 * <p>Test structures are NBT templates under {@code data/groundburst/structure/gametest/}, generated by
 * {@code tools/structure}.
 */
public final class GBGameTests {
    /** Structure with a 16x16 smooth-stone floor at y=0 and 15 blocks of air above. */
    public static final Identifier FLOOR_16 = GroundBurst.id("gametest/floor_16");
    /** A solid 12x12x12 cube of stone (rock for ore features to replace). */
    public static final Identifier STONE_12 = GroundBurst.id("gametest/stone_12");

    private static final List<TestSpec> SPECS = new ArrayList<>();

    /** A test: its name, the structure it runs in, its timeout, whether its plot has open sky, and what it does. */
    public record TestSpec(String name, Identifier structure, int maxTicks, boolean sky, Consumer<GameTestHelper> body) {}

    static {
        test("harness_floor", FLOOR_16, 20, helper -> {
            helper.assertBlockPresent(Blocks.SMOOTH_STONE, 0, 0, 0);
            helper.assertBlockPresent(Blocks.SMOOTH_STONE, 15, 0, 15);
            helper.assertBlockPresent(Blocks.AIR, 7, 1, 7);
            helper.succeed();
        });

        test("registry_names_and_tabs", FLOOR_16, 20, helper -> {
            GBItems.ITEMS.getEntries().forEach(entry -> {
                var item = entry.get();
                helper.assertTrue(GBLang.has(item.getDescriptionId()), "Item has no English name: " + entry.getId());
            });
            GBBlocks.BLOCKS.getEntries().forEach(entry ->
                    helper.assertTrue(GBLang.has(entry.get().getDescriptionId()), "Block has no English name: " + entry.getId()));
            helper.succeed();
        });

        ResourceTests.register();
        MachineTests.register();
        TallMachineTests.register();
        SideConfigTests.register();
        FluidMachineTests.register();
        MultiblockTests.register();
        FluidSystemTests.register();
        TankPumpTests.register();
        AdvancedMachineTests.register();
        PowerStorageTests.register();
        ReactorTests.register();
        FusionSingularityTests.register();
        PipeTests.register();
        BlastTests.register();
        OrdnanceTests.register();
        ChargeTests.register();
        MineTests.register();
        NavalTests.register();
        BombTests.register();
        EffectTests.register();
        AssemblyTests.register();
        MissileTests.register();
        StatsTests.register();
        NuclearTests.register();
        ExoticTests.register();
        UpgradeTests.register();
        StormTests.register();
        CryoTests.register();
        ParticleCannonTests.register();
        StrategicTests.register();
        SpecialWeaponsTests.register();
        DefenceTests.register();
        AlarmTests.register();
        AssemblerTests.register();
        LaunchTests.register();
        SiloTests.register();
        SuperweaponTests.register();
        CruiseTests.register();
        VlsTests.register();
        StationTests.register();
        DesignatorTests.register();
        SemiconductorTests.register();
        FactoryTests.register();
        RadiationTests.register();
        FalloutTests.register();
        AftermathTests.register();
        WastelandTests.register();
        StructureTests.register();
        ConstructionTests.register();
        ManualContentTests.register();
        ArtilleryTests.register();
        CarryTests.register();
        HullTests.register();
        HealTests.register();
    }

    private GBGameTests() {}

    static void test(String name, Identifier structure, int maxTicks, Consumer<GameTestHelper> body) {
        SPECS.add(new TestSpec(name, structure, maxTicks, false, body));
    }

    /** A test with open sky over its plot (no barrier lid), for things that fly above it. */
    static void testOpenSky(String name, Identifier structure, int maxTicks, Consumer<GameTestHelper> body) {
        SPECS.add(new TestSpec(name, structure, maxTicks, true, body));
    }

    /** Every test, in the order listed. */
    public static List<TestSpec> specs() {
        return java.util.Collections.unmodifiableList(SPECS);
    }

    public static void register(IEventBus modBus) {
        GameTestRegistration.register(modBus, SPECS);
    }
}
